def get_news_markets(market: str | None = None) -> dict[str, Any]:
    markets = NEWS_MARKETS
    if market:
        market_key = market.strip().lower()
        markets = [item for item in markets if item["id"] == market_key]

    return {
        "markets": deepcopy(markets),
        "meta": {
            "contentType": "research-sample",
            "disclaimer": "内置研究样例，不构成投资建议；接入实时资讯源后可由同一接口更新。",
        },
    }